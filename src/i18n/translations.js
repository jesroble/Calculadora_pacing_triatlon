// Aviso de desarrollo si es/en se desincronizan — trata los arrays (faq.items,
// cta.services) como hojas opacas, ya que su orden/longitud lo vigila el traductor,
// no un diff de claves.
if (import.meta.env.DEV) {
  const collectPaths = (obj, prefix = '') =>
    Object.entries(obj).flatMap(([key, value]) =>
      value && typeof value === 'object' && !Array.isArray(value)
        ? collectPaths(value, `${prefix}${key}.`)
        : [`${prefix}${key}`]
    )
  const esPaths = new Set(collectPaths(translations.es))
  const enPaths = new Set(collectPaths(translations.en))
  const missing = [
    ...[...esPaths].filter(k => !enPaths.has(k)).map(k => `en missing: ${k}`),
    ...[...enPaths].filter(k => !esPaths.has(k)).map(k => `es missing: ${k}`),
  ]
  if (missing.length) console.warn('[i18n] es/en key mismatch:', missing)
}
